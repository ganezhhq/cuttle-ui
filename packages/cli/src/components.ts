import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, posix, relative, sep } from 'node:path';
import { merge } from 'node-diff3';
import { resolveItems } from './registry';
import type { Registry, RegistryFile } from './registry';

export const DEFAULT_DIR = 'src/components/cuttle';
const BASE_DIR = '.cuttle/base';
const CONFLICT_MARKER = /^<{7} /m;

interface Config {
  framework: string | null;
  tokens: string;
  components?: string;
  /** The registry version each added item was last brought to. */
  installed?: Record<string, string>;
}

const readText = (path: string) => readFile(path, 'utf8').catch(() => null);

async function write(path: string, content: string) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

async function readConfig(cwd: string): Promise<Config> {
  const source = await readText(join(cwd, 'cuttle.json'));
  if (source === null) throw new Error('No cuttle.json found. Run "cuttle init" first.');
  const config = JSON.parse(source) as Config;
  if (config.framework !== 'react' && config.framework !== null) {
    throw new Error(`Only React is supported for now, but this project uses ${config.framework}.`);
  }
  return config;
}

const writeConfig = (cwd: string, config: Config) =>
  writeFile(join(cwd, 'cuttle.json'), `${JSON.stringify(config, null, 2)}\n`);

const NOTICE = 'Generated by cuttle, and replaced on every add and update.';

/** Rewrites the files that gather everything added so far into one import each. */
async function writeEntryFiles(cwd: string, dir: string, config: Config, registry: Registry) {
  const names = Object.keys(config.installed ?? {}).flatMap((name) =>
    (registry.items[name]?.files ?? []).map((file) => file.name),
  );
  const unique = [...new Set(names)].sort();

  const modules = unique
    .filter((name) => name.endsWith('.tsx') && name !== 'layer.tsx')
    .map((name) => `export * from './${name.replace(/\.tsx$/, '')}';`);
  await write(join(cwd, dir, 'index.ts'), `// ${NOTICE}\n${modules.join('\n')}\n`);

  const tokens = relative(join(cwd, dir), join(cwd, config.tokens)).split(sep).join(posix.sep);
  // base.css comes first, so components can override what it sets.
  const styles = unique
    .filter((name) => name.endsWith('.css'))
    .sort((a, b) => Number(b === 'base.css') - Number(a === 'base.css'));
  const imports = [tokens, ...styles.map((name) => `./${name}`)].map(
    (path) => `@import '${path}';`,
  );
  await write(join(cwd, dir, 'cuttle.css'), `/* ${NOTICE} */\n${imports.join('\n')}\n`);
}

async function addDependencies(cwd: string, dependencies: Record<string, string>) {
  const path = join(cwd, 'package.json');
  const source = await readText(path);
  if (source === null) return [];
  const pkg = JSON.parse(source) as {
    dependencies?: Record<string, string>;
    devDependencies?: Record<string, string>;
  };
  const missing = Object.entries(dependencies).filter(
    ([name]) => !pkg.dependencies?.[name] && !pkg.devDependencies?.[name],
  );
  if (missing.length === 0) return [];
  pkg.dependencies = Object.fromEntries(
    [...Object.entries(pkg.dependencies ?? {}), ...missing].sort(([a], [b]) => a.localeCompare(b)),
  );
  await writeFile(path, `${JSON.stringify(pkg, null, 2)}\n`);
  return missing.map(([name]) => name);
}

export interface AddOptions {
  cwd: string;
  registry: Registry;
  names: string[];
  dir?: string | undefined;
  overwrite?: boolean;
}

export interface AddResult {
  dir: string;
  added: string[];
  skipped: string[];
  dependencies: string[];
}

/** Copies components and what they depend on into the project. */
export async function add(options: AddOptions): Promise<AddResult> {
  const { cwd, registry, names, overwrite = false } = options;
  const config = await readConfig(cwd);
  const dir = options.dir ?? config.components ?? DEFAULT_DIR;
  const items = resolveItems(registry, names);
  const installed = { ...config.installed };

  // Checks everything first, so a clash never leaves a half-finished add behind.
  const newItems = items.filter((name) => !installed[name]);
  const tracked = new Set(
    Object.keys(installed).flatMap((name) =>
      (registry.items[name]?.files ?? []).map((file) => file.name),
    ),
  );
  const files = new Map<string, RegistryFile>();
  for (const name of newItems) {
    for (const file of registry.items[name]?.files ?? []) {
      if (!tracked.has(file.name)) files.set(file.name, file);
    }
  }
  if (!overwrite) {
    for (const file of files.values()) {
      const existing = await readText(join(cwd, dir, file.name));
      if (existing !== null && normalize(existing) !== normalize(file.content)) {
        throw new Error(
          `${posix.join(dir, file.name)} already exists with different content. Use --force to replace it.`,
        );
      }
    }
  }

  for (const file of files.values()) {
    await write(join(cwd, dir, file.name), file.content);
    await write(join(cwd, BASE_DIR, file.name), file.content);
  }

  const dependencies: Record<string, string> = {};
  for (const name of newItems) {
    Object.assign(dependencies, registry.items[name]?.dependencies);
    installed[name] = registry.version;
  }
  const next: Config = { ...config, components: dir, installed };
  await writeConfig(cwd, next);
  await writeEntryFiles(cwd, dir, next, registry);

  return {
    dir,
    added: newItems,
    skipped: items.filter((name) => !newItems.includes(name)),
    dependencies: await addDependencies(cwd, dependencies),
  };
}

const normalize = (text: string) => text.replace(/\r\n/g, '\n');
const usesCrlf = (text: string) => text.includes('\r\n');

export type UpdateStatus =
  | 'up-to-date'
  | 'kept-changes'
  | 'updated'
  | 'merged'
  | 'added'
  | 'restored'
  | 'conflict'
  | 'unresolved';

export interface UpdateEntry {
  file: string;
  status: UpdateStatus;
}

export interface MergeResult {
  text: string;
  conflict: boolean;
}

/** A 3-way merge of your copy and the new version, using the version you started from. */
export function mergeFile(local: string, base: string, incoming: string): MergeResult {
  const { conflict, result } = merge(local.split('\n'), base.split('\n'), incoming.split('\n'), {
    label: { a: 'your changes', b: 'cuttle update' },
  });
  return { text: result.join('\n'), conflict };
}

/** Decides what should happen to one file, without touching the disk. */
export function planFile(
  local: string | null,
  base: string | null,
  incoming: string,
): { status: UpdateStatus; content: string | null } {
  const next = normalize(incoming);
  if (local === null) return { status: base === null ? 'added' : 'restored', content: incoming };

  const mine = normalize(local);
  const restoreEol = (text: string) => (usesCrlf(local) ? text.replace(/\n/g, '\r\n') : text);
  if (CONFLICT_MARKER.test(mine)) return { status: 'unresolved', content: null };
  if (mine === next) return { status: 'up-to-date', content: null };

  // Without a saved starting point, an empty base makes every difference a conflict.
  const previous = normalize(base ?? '');
  if (previous === next) return { status: 'kept-changes', content: null };
  if (mine === previous) return { status: 'updated', content: restoreEol(next) };

  const { text, conflict } = mergeFile(mine, previous, next);
  return { status: conflict ? 'conflict' : 'merged', content: restoreEol(text) };
}

export interface UpdateOptions {
  cwd: string;
  registry: Registry;
  /** Leave it empty to update everything that was added. */
  names: string[];
  dryRun?: boolean;
}

export interface UpdateResult {
  entries: UpdateEntry[];
  dependencies: string[];
  hasConflicts: boolean;
}

/** Brings added components to the current version, and keeps local changes. */
export async function update(options: UpdateOptions): Promise<UpdateResult> {
  const { cwd, registry, names, dryRun = false } = options;
  const config = await readConfig(cwd);
  const dir = config.components ?? DEFAULT_DIR;
  const installed = { ...config.installed };

  for (const name of names) {
    if (!registry.items[name]) throw new Error(`Unknown component "${name}".`);
    if (!installed[name])
      throw new Error(`"${name}" has not been added. Use "cuttle add ${name}".`);
  }
  const requested = names.length > 0 ? names : Object.keys(installed);
  const items = resolveItems(
    registry,
    requested.filter((name) => registry.items[name]),
  );

  const entries: UpdateEntry[] = [];
  const dependencies: Record<string, string> = {};
  const done = new Set<string>();

  for (const name of items) {
    const item = registry.items[name];
    if (!item) continue;
    Object.assign(dependencies, item.dependencies);
    for (const file of item.files) {
      if (done.has(file.name)) continue;
      done.add(file.name);
      const path = join(cwd, dir, file.name);
      const basePath = join(cwd, BASE_DIR, file.name);
      const { status, content } = planFile(
        await readText(path),
        await readText(basePath),
        file.content,
      );
      entries.push({ file: posix.join(dir, file.name), status });
      if (dryRun) continue;
      if (content !== null) await write(path, content);
      // An unresolved file keeps its old base, so the next run can still merge it.
      if (status !== 'unresolved') await write(basePath, file.content);
    }
    if (!dryRun) installed[name] = registry.version;
  }

  const added = dryRun ? [] : await addDependencies(cwd, dependencies);
  if (!dryRun) {
    const next: Config = { ...config, components: dir, installed };
    await writeConfig(cwd, next);
    await writeEntryFiles(cwd, dir, next, registry);
  }

  return {
    entries,
    dependencies: added,
    hasConflicts: entries.some(({ status }) => status === 'conflict' || status === 'unresolved'),
  };
}
